/**
 * Shuffles options for a challenge so the correct option is not always first,
 * and ensures completely unique IDs to prevent key or scale collisions.
 */
function randomizeChallengeOptions(options: GameOption[], challengeId: string): GameOption[] {
  const cloned = options.map((opt, idx) => ({
    ...opt,
    id: `${challengeId}_opt_${idx}_${Math.random().toString(36).substring(2, 6)}`,
  }));

  // Fisher-Yates shuffle
  for (let i = cloned.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [cloned[i], cloned[j]] = [cloned[j], cloned[i]];
  }
  return cloned;
}

/**
 * Intelligent session generator for Unit 1:
 * - Picks 1 challenge for each of the 4 waypoints from the authentic pool.
 * - Filters out recently played challenge IDs so the child never sees repeats in a session.
 * - Randomizes option orders so correct answers are not fixed at index 0.
 * - Preserves curriculum grounding and mastery metrics.
 */
export const generateUnit1GameSession = (excludeChallengeIds: string[] = []): GameDefinition => {
  const baseGame = MOCK_GAME_DATABASE['1.1'];
  const selectedChallenges: GameChallenge[] = [];

  for (let waypoint = 0; waypoint < 4; waypoint++) {
    const candidates = UNIT1_CHALLENGE_POOL.filter((c) => c.waypointIndex === waypoint);
    // Filter out recently excluded to prevent immediate repeats
    let pool = candidates.filter((c) => !excludeChallengeIds.includes(c.id));
    if (pool.length === 0) {
      pool = candidates; // Fallback if all have been played
    }

    // Pick random candidate
    const picked = pool[Math.floor(Math.random() * pool.length)] || candidates[0];

    selectedChallenges.push({
      id: picked.id,
      questionId: picked.questionId,
      conceptId: picked.conceptId,
      challengeType: picked.challengeType,
      promptText: picked.promptText,
      targetWord: picked.targetWord,
      targetVisual: picked.targetVisual,
      hintText: picked.hintText,
      correctExplanation: picked.correctExplanation,
      options: randomizeChallengeOptions(picked.options, picked.id),
    });
  }

  return {
    ...baseGame,
    challenges: selectedChallenges,
  };
};

/**
 * Intelligent helper to fetch a game for a given lesson or unit fallback
 */
export const getGameForLesson = (lessonId: string): GameDefinition => {
  if (MOCK_GAME_DATABASE[lessonId]) {
    return MOCK_GAME_DATABASE[lessonId];
  }
  // Check unit prefix (e.g. '2.3' -> Unit 2, '3.2' -> Unit 3, '4.2' -> Unit 4)
  const prefix = lessonId ? String(lessonId).split('.')[0] : '1';
  if (prefix === '2') {
    return MOCK_GAME_DATABASE['2.1'] || MOCK_GAME_DATABASE['1.1'];
  }
  if (prefix === '3') {
    return MOCK_GAME_DATABASE['3.1'] || MOCK_GAME_DATABASE['1.1'];
  }
  if (prefix === '4') {
    return MOCK_GAME_DATABASE['4.1'] || MOCK_GAME_DATABASE['1.1'];
  }
  return MOCK_GAME_DATABASE['1.1'];
};

